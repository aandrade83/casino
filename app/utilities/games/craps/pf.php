    <h2>How does it work?</h2>

<p>
To prove that neither you nor us can possibly know what will be the result of the dices, we use two different numbers, one generated from our server and the other generated by your browser (Can be edited manually if you want), the combination of this numbers will be used to create the dices result.
</p>

<h2>Details of the process</h2>

<p>Before each spin our server generates one 12 dygit number composed of 2 parts, first 6 digyts are the numbers from 1 to 6 in a random order and last 6 digyts are also the numbers from 1 to 6 in a diferent random order (<strong>SERVER #</strong>), this number is encrypted using 2 secret keys (<strong>SECRETS</strong>) and then is displayed to you (Find it at the top of your craps table). At the same time your browser generates a pair of numbers between 1 and 6 (<strong>PLAYER #</strong>) (this numbers can be edited by you, is located at the top of your craps table). At the moment you make your roll, your browser will send the <strong>PLAYER #</strong> to our server, then we will get the dice result from the  <strong>SERVER #</strong> getting the digits  on the positions defined by <strong>PLAYER #</strong>. For example, if <strong>SERVER #</strong> is 451236312654 and <strong>PLAYER #</strong> is 1,3 , the dices results will be 4 and 2 (Position 1 in the first part of <strong>PLAYER #</strong> is 4 and position 3 in the second part of <strong>PLAYER #</strong> is 2). Finally the results will be displayed, including the <strong>SECRET KEYS</strong> used to encrypt the <strong>SERVER #</strong>, the <strong>SERVER #</strong> decrypted, the <strong>PLAYER #</strong> provided by you and the <strong>FINAL NUMBER</strong> used to get the dices results, with this information you can verify that the 
<strong>SERVER #</strong> wasn't changed and that your roll result was completely random.</p>


<h3>How the SERVER # is encrypted?</h3>
<p>
The <strong>SERVER #</strong> is encrypted with the <strong>SECRET KEYS</strong> using the <strong>BCRYPT</strong> hashing function, the encryption is made in the following way: <strong>BCRYPT(SECRET1+SERVER#+SECRET2)</strong>
</p>
