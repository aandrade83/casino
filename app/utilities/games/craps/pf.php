<h2>What happen if I insert an Invalid PLAYER #</h2>
<p>
<strong>PLAYER #</strong> should be a pair of numbers from 1 to 6, separate by comma (Example: <strong>3,2</strong>).
</p>
<p>
If by mistake or intentionally you insert a non numeric entry or a number lower or higher than the limits as the <strong>PLAYER #</strong>, our server will use <strong>1</strong> as your <strong>PLAYER #</strong>
</p>

    
