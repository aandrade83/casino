    <h2>How does it work?</h2>

<p>
To prove that neither you nor us can possibly know how the cards will be shuffle, we use two different numbers, one generated from our server and the other generated by your browser (Can be edited manually if you want), the sum of this  numbers is used to shuffle the game cards.
</p>

<h2>Details of the process</h2>

<p>Before each hand our server generates one number between 0 and 100000000 (<strong>SERVER #</strong>), this number is encrypted using 2 secret keys (<strong>SECRETS</strong>) and then is displayed to you (Find it at the top of your game table). At the same time your browser generates another number between 0 and 100000000 (<strong>PLAYER #</strong>) (this numbers can be edited by you, is located at the top of your game table). At the moment you deal, your browser will send the <strong>PLAYER #</strong> to our server, and then it will add the <strong>SERVER #</strong> to it, the final number will be used to shuffle the game cards (If the sum of both numbers is higher than 100000000 then we will subtract  100000000 to it). For example, if <strong>SERVER #</strong> is 9856214 and <strong>PLAYER #</strong> is 994122, the number used to shuffle the cards will be 10850336. Finally the results will be displayed, including the <strong>SECRET KEYS</strong> used to encrypt the <strong>SERVER #</strong>, the <strong>SERVER #</strong> decrypted, the <strong>PLAYER #</strong> provided by you and the <strong>FINAL NUMBER</strong> used to shuffle the cards, with this information you can verify that the 
<strong>SERVER #</strong> wasn't changed and that the shuffle was completely random.</p>

<h3>Cards shuffle</h3>
<p>The game uses a total of <strong><? echo $game->number_of_decks ?></strong> decks, the original deck layout is spades, hearts, diamonds, clubs from <strong>A to K</strong>. SA, S2, S3 .. SK ... HA, H2, H3 .. HK ... DA, D2, D3 .. DK ... CA, C2, C3 .. CK, and each card is repeated the number of decks, for example, for 2 decks: SA, SA, S2,S2, S3,S3 .. SK,SK ... HA,HA, H2,H2, H3,H3 .. HK,HK ... DA,DA, D2,D2, D3,D3 .. DK,DK ... CA,CA, C2,C2, C3,C3 .. CK,CK. Then we use the sum of <strong>SERVER #</strong> + <strong>PLAYER #</strong> to seed the <strong>Mersenne Twister RNG</strong> algorithm and generate a list of random numbers, finally we shuffle the cards based on the random numbers list. 
<br /><br />You can use <a href="#tool">the tool</a> at the end of this page or <a href="utilities/download/shuffle.rar">download the source code</a> to verify a shuffle with an specific seed.
</p>

<h3>How the SERVER # is encrypted?</h3>
<p>
The <strong>SERVER #</strong> is encrypted with the <strong>SECRET KEYS</strong> using the <strong>BCRYPT</strong> hashing function, the encryption is made in the following way: <strong>BCRYPT(SECRET1+SERVER#+SECRET2)</strong>
</p>
