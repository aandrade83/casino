    <h2>How does it work?</h2>
<p>
First of all you need to know that we have <a href="#result_table">a table of possible results</a> for each reel, that means that every time you spin, randomly we choose one of the results in this table.</p><p>* This table will not change so each position of the table will always have the same result.
</p>

<p>
To prove that neither you nor us can possibly know what position of the table will be choose to get a result, we use two different numbers, one generated from our server and the other generated by your browser (Can be edited manually if you want), the sum of this two numbers is used to get a result from the <a href="#result_table">results table</a>.
</p>

<h2>Details of the process</h2>

<p>Before each spin our server generates a random number between 1.000.000 and 1.999.999 (<strong>SERVER #</strong>), this number is encrypted using 2 secret keys (<strong>SECRETS</strong>) and then is displayed to you (Find it at the top of your slot machine). At the same time your browser generates another random number between 1.000.000 and 1.999.999 (<strong>PLAYER #</strong>) (this number can be edited by you, is located at the top of your slot machine). At the moment you make your spin, your browser will send the <strong>PLAYER #</strong> to our server, and then it will add the <strong>SERVER #</strong> to it, the final number will be used to get a result from the <a href="#result_table">results table</a> in the following way: last 6 digits will determine the 3 reels positions, for example the number <strong>1571609</strong> will get position <strong>57</strong> for reel 1, position <strong>16</strong> for reel 2 and position <strong>09</strong> for reel 3. Finally spin results will be displayed, including the <strong>SECRET KEYS</strong> used to encrypt the <strong>SERVER #</strong>, the <strong>SERVER #</strong> decrypted, the <strong>PLAYER #</strong> provided by you and the <strong>FINAL POSITION</strong> used to get the result, with this information you can verify that the 
<strong>SERVER #</strong> wasn't changed and that your spin result was completely random.</p>

<h3>How the SERVER # is encrypted?</h3>
<p>
The <strong>SERVER #</strong> is encrypted with the <strong>SECRET KEYS</strong> using the <strong>BCRYPT</strong> hashing function, the encryption is made in the following way: <strong>BCRYPT(SECRET1+SERVER#+SECRET2)</strong>
</p>
