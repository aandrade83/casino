</p>

<h2>What happen if I insert an Invalid PLAYER #</h2>
<p>
<strong>PLAYER #</strong> should be a integer number between 1.000.000 and 1.999.999
</p>
<p>
If by mistake or intentionally you insert a non numeric entry or a number lower or higher than the limits as the <strong>PLAYER #</strong>, our server will use <strong>1.000.000</strong> as your <strong>PLAYER #</strong>
</p>

<h2>*DOES THE RESULTS TABLE EVER CHANGE?</h2>
<p>
The <strong>RESULTS TABLE</strong> is not meant to change, you can store a local copy of the <a href="#result_table">Results Table</a> to constantly verify that it haven't change.
</p>
<p>
However, it could be possible that we have to make some adjustments on the <strong>RESULTS TABLE</strong>, in this case, we will notify players in advance.
</p>


